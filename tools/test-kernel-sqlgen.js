// 生成器 SQL 接线回归：旧 IR -> 元模型 -> MySQL/PostgreSQL/SQLite DDL。
const assert = require('assert');
const { DatabaseSync } = require('node:sqlite');
const ir = require('../app/generator/ir');
const { generateSql } = require('../app/generator/sql');

const project = ir.normalizeProject({
  name: 'SQL 生成验收',
  idStrategy: 'auto',
  modules: [],
  customTables: [{
    name: 'biz_order',
    comment: '订单',
    columns: [
      { name: 'id', type: 'bigint', pk: true, auto: true, required: true, comment: '主键' },
      { name: 'order_no', type: 'varchar(64)', required: true, comment: '单号' },
      { name: 'amount', type: 'decimal(18,2)', required: true, comment: '金额' },
      { name: 'created_at', type: 'datetime', comment: '创建时间' },
      { name: 'updated_at', type: 'datetime', comment: '更新时间' },
    ],
  }],
});

let passed = 0;
function test(name, fn) {
  try { fn(); passed++; console.log(`ok   ${name}`); } catch (err) { console.log(`FAIL ${name}: ${err.message}`); process.exitCode = 1; }
}

test('MySQL：自增、InnoDB、更新时间', () => {
  const r = generateSql(project, { dialect: 'mysql' });
  const sql = r.files.find((f) => f.path.includes('custom-biz-order')).content;
  assert.match(sql, /`id` BIGINT AUTO_INCREMENT NOT NULL/);
  assert.match(sql, /ENGINE=InnoDB/);
  assert.match(sql, /ON UPDATE CURRENT_TIMESTAMP/);
  assert.match(sql, /DECIMAL\(18,2\)/);
});

test('PostgreSQL：identity、numeric、timestamp', () => {
  const r = generateSql(project, { dialect: 'postgres' });
  const sql = r.files.find((f) => f.path.includes('custom-biz-order')).content;
  assert.match(sql, /"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
  assert.match(sql, /"amount" NUMERIC\(18,2\)/);
  assert.match(sql, /"created_at" TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP/);
  assert.doesNotMatch(sql, /AUTO_INCREMENT/);
});

test('SQLite：可真正执行建表与索引', () => {
  const r = generateSql(project, { dialect: 'sqlite' });
  const sql = r.files.filter((f) => f.path !== 'sql/06_seed.sql').map((f) => f.content).join('\n');
  assert.match(sql, /"id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL/);
  assert.doesNotMatch(sql, /AUTO_INCREMENT/);
  const db = new DatabaseSync(':memory:');
  try {
    db.exec(sql);
    const tables = db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").all().map((x) => x.name);
    assert.ok(tables.includes('biz_order'));
    assert.ok(tables.includes('sys_user'));
  } finally { db.close(); }
});

test('非 MySQL 的 seed 文件明确说明不直接执行', () => {
  const r = generateSql(project, { dialect: 'postgres' });
  const seed = r.files.find((f) => f.path.endsWith('_seed.sql')).content;
  assert.match(seed, /仍按 MySQL 语法编写/);
});

console.log(`\n${passed} passed`);
