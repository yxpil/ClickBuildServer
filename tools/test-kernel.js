test('元模型：实体/字段/关联/枚举/规则归一化', () => {
  const v = validateRegistry(sample);
  assert.strictEqual(v.ok, true, v.errors.join(';'));
  assert.strictEqual(sample.entities.length, 4);
  assert.strictEqual(sample.entities[0].primaryKey, 'id');
  assert.strictEqual(sample.enums[0].values.length, 2);
  assert.strictEqual(sample.rules[0].kind, 'pattern');
});

test('元模型：坏关联和坏枚举会被抓住', () => {
  const bad = normalizeRegistry({
    entities: [{ name: 'a', fields: [{ name: 'id', type: 'bigint', pk: true }, { name: 'x', type: 'varchar', enumRef: 'nope' }], relations: [{ kind: 'many-to-one', target: 'ghost', field: 'x' }] }],
  });
  const v = validateRegistry(bad);
  assert.ok(v.errors.some((x) => x.includes('目标不存在')));
  assert.ok(v.errors.some((x) => x.includes('枚举')));
});

test('方言：MySQL 自增/注释/引擎', () => {
  const ddl = dialectOf('mysql').createTable(sample.entities[0]).join('\n');
  assert.match(ddl, /`id` BIGINT AUTO_INCREMENT NOT NULL/);
  assert.match(ddl, /PRIMARY KEY \(`id`\)/);
  assert.match(ddl, /ENGINE=InnoDB/);
  assert.match(ddl, /COMMENT='用户表'/);
  assert.match(ddl, /UNIQUE \(`email`\)/);
});

test('方言：PostgreSQL identity/jsonb/comment', () => {
  const ddl = dialectOf('postgres').createTable(sample.entities[0]).join('\n');
  assert.match(ddl, /"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
  assert.match(ddl, /"profile" JSONB NULL/);
  assert.match(ddl, /COMMENT ON TABLE "users" IS '用户表'/);
  assert.match(ddl, /COMMENT ON COLUMN "users"\."id" IS '主键'/);
});

test('方言：SQLite integer pk autoincrement', () => {
  const ddl = dialectOf('sqlite').createTable(sample.entities[0]).join('\n');
  assert.match(ddl, /"id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL/);
  assert.match(ddl, /"profile" TEXT NULL/);
  assert.doesNotMatch(ddl, /PRIMARY KEY \("id"\)/);
});

test('元模型：复合主键', () => {
  const reg = normalizeRegistry({
    entities: [{
      name: 'post_tags',
      primaryKeys: ['post_id', 'tag_id'],
      fields: [{ name: 'post_id', type: 'bigint' }, { name: 'tag_id', type: 'bigint' }],
    }],
  });
  assert.strictEqual(validateRegistry(reg).ok, true);
  assert.deepStrictEqual(reg.entities[0].primaryKeys, ['post_id', 'tag_id']);
  assert.match(dialectOf('mysql').createTable(reg.entities[0]).join('\n'), /PRIMARY KEY \(`post_id`, `tag_id`\)/);
});

test('迁移：SQLite 初始化可执行并记录版本', () => {
  const db = new DatabaseSync(':memory:');
  try {
    const m = initMigration(sample, 'sqlite', { version: '0001' });
    applySqlite(db, m);
    const tables = db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").all().map((x) => x.name);
    assert.deepStrictEqual(tables.sort(), ['post_tags', 'posts', 'schema_migrations', 'tags', 'users']);
    const applied = db.prepare('SELECT version FROM schema_migrations').all().map((x) => x.version);
    assert.deepStrictEqual(applied, ['0001']);
    const idx = db.prepare("SELECT name FROM sqlite_master WHERE type='index' AND name='uk_post_tag'").all();
    assert.strictEqual(idx.length, 1);
  } finally { db.close(); }
});

test('迁移：SQLite 改字段/加字段/加索引并保留数据', () => {
  const db = new DatabaseSync(':memory:');
  try {
    applySqlite(db, initMigration(sample, 'sqlite', { version: '0001' }));
    db.exec("INSERT INTO users (email, status) VALUES ('a@b.c', 'active')");
    const next = normalizeRegistry({
      ...sample,
      version: 2,
      entities: sample.entities.map((e) => e.name !== 'users' ? e : {
        ...e,
        fields: e.fields.map((f) => f.name === 'email' ? { ...f, length: 512, nullable: false } : f).concat([{ name: 'display_name', type: 'varchar', length: 80, nullable: true }]),
        indexes: (e.indexes || []).concat([{ name: 'idx_users_display', columns: ['display_name'] }]),
      }),
    });
    const m = diffMigration(sample, next, 'sqlite', { version: '0002' });
    assert.match(m.up.join('\n'), /__cb_tmp_users/);
    assert.match(m.up.join('\n'), /idx_users_display/);
    applySqlite(db, m);
    const row = db.prepare('SELECT id, email FROM users').get();
    assert.strictEqual(row.email, 'a@b.c');
    assert.strictEqual(db.prepare("SELECT name FROM sqlite_master WHERE type='index' AND name='idx_users_display'").all().length, 1);
    rollbackSqlite(db, m);
    const cols = db.prepare('PRAGMA table_info(users)').all().map((x) => x.name);
    assert.ok(!cols.includes('display_name'));
    assert.strictEqual(db.prepare('SELECT email FROM users').get().email, 'a@b.c');
  } finally { db.close(); }
});

test('迁移：MySQL ALTER 生成 ADD/MODIFY/INDEX', () => {
  const next = normalizeRegistry({
    ...sample,
    entities: sample.entities.map((e) => e.name !== 'users' ? e : {
      ...e,
      fields: e.fields.map((f) => f.name === 'email' ? { ...f, length: 512, nullable: false } : f).concat([{ name: 'display_name', type: 'varchar', length: 80 }]),
    }),
  });
  const m = diffMigration(sample, next, 'mysql', { version: '0002' });
  const sql = m.up.join('\n');
  assert.match(sql, /ALTER TABLE `users` ADD COLUMN `display_name`/);
  assert.match(sql, /MODIFY COLUMN `email` VARCHAR\(512\) NOT NULL/);
});

test('迁移：PostgreSQL ALTER 生成 TYPE/DEFAULT/NOT NULL', () => {
  const next = normalizeRegistry({
    ...sample,
    entities: sample.entities.map((e) => e.name !== 'users' ? e : {
      ...e,
      fields: e.fields.map((f) => f.name === 'email' ? { ...f, length: 512, nullable: false, default: 'x@y.z' } : f),
    }),
  });
  const m = diffMigration(sample, next, 'postgres', { version: '0002' });
  const sql = m.up.join('\n');
  assert.match(sql, /ALTER COLUMN "email" TYPE VARCHAR\(512\) USING "email"::VARCHAR\(512\)/);
  assert.match(sql, /SET DEFAULT 'x@y\.z'/);
  assert.match(sql, /SET NOT NULL/);
});

test('迁移：文件带 checksum 和 UP/DOWN', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cb-kernel-'));
  const m = initMigration(sample, 'mysql', { version: '0001', name: 'init' });
  const file = writeMigration(m, dir);
  const text = fs.readFileSync(file, 'utf8');
  assert.match(text, /^-- ClickBuild migration 0001/);
  assert.match(text, /checksum: [a-f0-9]{64}/);
  assert.match(text, /-- >>> UP/);
  assert.match(text, /-- >>> DOWN/);
  assert.strictEqual(m.checksum.length, 64);
});

test('工程适配：26 套案例 0 个元模型错误，SQLite 全部可初始化', () => {
  const dir = path.join(__dirname, '..', 'app', 'iface', 'cases');
  const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json'));
  assert.ok(files.length >= 20);
  let entities = 0;
  for (const file of files) {
    const p = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    const reg = registryFromProject(p);
    const v = validateRegistry(reg);
    assert.strictEqual(v.ok, true, `${file}: ${v.errors.slice(0, 3).join(';')}`);
    entities += reg.entities.length;
    const db = new DatabaseSync(':memory:');
    try { applySqlite(db, initMigration(reg, 'sqlite', { version: '0001' })); } finally { db.close(); }
  }
  assert.ok(entities > 100, `实体数 ${entities}`);
});

test('工程适配：同名物理表合并并留下导入提示', () => {
  const p = {
    name: '重复表',
    interfaces: [
      { id: 'a', name: 'A', tables: [{ key: 'main', name: 'shared', fields: [{ name: 'id', type: 'bigint', pk: true }, { name: 'a', type: 'varchar' }] }] },
      { id: 'b', name: 'B', tables: [{ key: 'main', name: 'shared', fields: [{ name: 'id', type: 'bigint', pk: true }, { name: 'a', type: 'varchar' }, { name: 'b', type: 'int' }] }] },
    ],
  };
  const reg = registryFromProject(p);
  assert.strictEqual(reg.entities.length, 1);
  assert.strictEqual(reg.entities[0].fields.length, 3);
  assert.ok(reg.options.importWarnings.some((x) => x.includes('重复定义')));
});

test('反向工程桥：元模型 -> 工程 JSON -> normalize -> 校验', () => {
  const project = projectFromRegistry(sample, { name: '导入工程' });
  const normalized = spec.normalizeProject(project);
  const v = spec.validateProject(normalized);
  assert.strictEqual(v.errors.length, 0, v.errors.join(';'));
  assert.strictEqual(normalized.interfaces.length, 4);
  assert.strictEqual(normalized.interfaces.reduce((n, i) => n + i.routes.length, 0), 20);
  assert.ok(normalized.interfaces[0].tables[0].fields.some((f) => f.name === 'email'));
});

test('SQLite 反向工程：读回表/字段/索引', () => {
  const db = new DatabaseSync(':memory:');
  try {
    applySqlite(db, initMigration(sample, 'sqlite', { version: '0001' }));
    const { introspectSqlite } = require('../app/kernel/introspect');
    const back = introspectSqlite(db);
    const users = back.entities.find((x) => x.name === 'users');
    assert.ok(users);
    assert.strictEqual(users.fields.find((f) => f.name === 'email').nullable, false);
    assert.ok(users.indexes.some((x) => x.name === 'idx_users_status'));
    assert.ok(!back.entities.some((x) => x.name === 'schema_migrations'));
  } finally { db.close(); }
});

